//! Provider-neutral OAuth authorization attempt tracking.
//!
//! The concrete provider generates unpredictable state/PKCE/nonce, binds the
//! listener or device authorization, validates the callback, verifies identity,
//! and durably stores credentials *before* invoking `complete`. This module
//! never handles a token, a callback code, or a credential and cannot grant
//! authority on the basis of a displayed browser challenge.
use super::{error, ATTEMPT_TTL, MAX_PENDING};
use phenix_provider_contracts::{
    AuthAttemptQuery, AuthAttemptState, AuthChallenge, AuthStart, AuthenticatedProfile,
    ProviderError, ProviderErrorCode,
};
use std::collections::BTreeMap;
use std::time::Instant;

struct Attempt {
    owner: AuthStart,
    started: Instant,
    challenge: AuthChallenge,
    announce: bool,
}

/// One provider-local, bounded registry of browser and device authorization
/// attempts. The challenge ID is generated by the provider's OAuth library,
/// must be unpredictable, and is not an authority token.
#[derive(Default)]
pub struct OAuthAttempts {
    pending: BTreeMap<String, Attempt>,
}

fn challenge_id(challenge: &AuthChallenge) -> Result<&str, ProviderError> {
    let (id, uri) = match challenge {
        AuthChallenge::OpenBrowser { attempt_id, url } => (attempt_id.as_str(), url.as_str()),
        AuthChallenge::DeviceAuthorization {
            attempt_id,
            verification_url,
            user_code,
        } => {
            if user_code.is_empty()
                || user_code.len() > 128
                || user_code.chars().any(char::is_control)
            {
                return Err(error(
                    ProviderErrorCode::InvalidInput,
                    "invalid OAuth device code",
                ));
            }
            (attempt_id.as_str(), verification_url.as_str())
        }
        AuthChallenge::ApiKeyInput { .. } => {
            return Err(error(
                ProviderErrorCode::InvalidInput,
                "expected OAuth challenge",
            ));
        }
    };
    // A short sequential ID must not stand in for the provider's random OAuth
    // correlation key. The callback state is separately validated by its
    // implementing strategy; this public ID never authenticates an account.
    if !(24..=256).contains(&id.len())
        || !id
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
    {
        return Err(error(
            ProviderErrorCode::InvalidInput,
            "invalid OAuth attempt identity",
        ));
    }
    // This is an additional defense. The provider validates the complete
    // URL and exact trusted OAuth endpoint before presenting the challenge.
    let authority = uri
        .strip_prefix("https://")
        .and_then(|url| url.split(['/', '?', '#']).next())
        .unwrap_or("");
    if uri.len() > 4096
        || authority.is_empty()
        || authority.contains('@')
        || uri
            .bytes()
            .any(|b| b.is_ascii_whitespace() || b.is_ascii_control() || b == b'\\')
    {
        return Err(error(
            ProviderErrorCode::InvalidInput,
            "invalid OAuth challenge URL",
        ));
    }
    Ok(id)
}

fn valid_owner(owner: &AuthStart) -> bool {
    [
        &owner.scope,
        &owner.provider_id,
        &owner.connection_id,
        &owner.method_id,
    ]
    .iter()
    .all(|s| !s.is_empty() && s.len() <= 128 && !s.chars().any(char::is_control))
}
fn owns(owner: &AuthStart, query: &AuthAttemptQuery) -> bool {
    owner.scope == query.scope
        && owner.provider_id == query.provider_id
        && owner.connection_id == query.connection_id
        && query.attempt_id.len() >= 24
}
fn unknown() -> ProviderError {
    error(ProviderErrorCode::NotFound, "OAuth attempt not found")
}

impl OAuthAttempts {
    /// A browser challenge is never itself a successful authentication.
    pub fn begin(
        &mut self,
        owner: AuthStart,
        challenge: AuthChallenge,
    ) -> Result<AuthChallenge, ProviderError> {
        if !valid_owner(&owner) {
            return Err(error(
                ProviderErrorCode::InvalidInput,
                "invalid OAuth owner",
            ));
        }
        let id = challenge_id(&challenge)?.to_owned();
        self.pending
            .retain(|_, item| item.started.elapsed() <= ATTEMPT_TTL);
        if self.pending.len() >= MAX_PENDING {
            return Err(error(
                ProviderErrorCode::Unavailable,
                "too many OAuth attempts",
            ));
        }
        if self.pending.contains_key(&id) {
            return Err(error(
                ProviderErrorCode::Conflict,
                "OAuth attempt already registered",
            ));
        }
        self.pending.insert(
            id,
            Attempt {
                owner,
                started: Instant::now(),
                challenge: challenge.clone(),
                announce: false,
            },
        );
        Ok(challenge)
    }

    fn check(
        &mut self,
        query: &AuthAttemptQuery,
    ) -> Result<Option<AuthAttemptState>, ProviderError> {
        let item = self.pending.get(&query.attempt_id).ok_or_else(unknown)?;
        if !owns(&item.owner, query) {
            return Err(unknown());
        }
        if item.started.elapsed() > ATTEMPT_TTL {
            self.pending.remove(&query.attempt_id);
            return Ok(Some(AuthAttemptState::Expired));
        }
        Ok(None)
    }

    /// Browser/device callbacks are handled in the provider. Polling this
    /// registry only returns pending state or a newly issued challenge.
    pub fn poll(&mut self, query: &AuthAttemptQuery) -> Result<AuthAttemptState, ProviderError> {
        if let Some(terminal) = self.check(query)? {
            return Ok(terminal);
        }
        let item = self
            .pending
            .get_mut(&query.attempt_id)
            .ok_or_else(unknown)?;
        if item.announce {
            item.announce = false;
            Ok(AuthAttemptState::AwaitingInput {
                challenge: item.challenge.clone(),
            })
        } else {
            Ok(AuthAttemptState::Pending)
        }
    }

    /// A provider may reissue a browser/device challenge for the *same* flow.
    /// Rotating the OAuth callback state is independently provider-controlled.
    pub fn reissue(
        &mut self,
        query: &AuthAttemptQuery,
        challenge: AuthChallenge,
    ) -> Result<(), ProviderError> {
        if let Some(_) = self.check(query)? {
            return Err(unknown());
        }
        if challenge_id(&challenge)? != query.attempt_id {
            return Err(error(
                ProviderErrorCode::InvalidInput,
                "OAuth challenge identity changed",
            ));
        }
        let item = self
            .pending
            .get_mut(&query.attempt_id)
            .ok_or_else(unknown)?;
        item.challenge = challenge;
        item.announce = true;
        Ok(())
    }

    /// Call only after the owning provider has cryptographically verified
    /// identity and persisted/authorized the token for this account.
    pub fn complete(
        &mut self,
        query: &AuthAttemptQuery,
        profile: AuthenticatedProfile,
    ) -> Result<AuthAttemptState, ProviderError> {
        if let Some(terminal) = self.check(query)? {
            return Ok(terminal);
        }
        let item = self.pending.get(&query.attempt_id).ok_or_else(unknown)?;
        if profile.id.is_empty()
            || profile.id.len() > 256
            || profile.label.is_empty()
            || profile.method_id != item.owner.method_id
        {
            return Err(error(
                ProviderErrorCode::InvalidInput,
                "verified OAuth profile mismatch",
            ));
        }
        self.pending.remove(&query.attempt_id);
        Ok(AuthAttemptState::Completed { profile })
    }

    pub fn fail(
        &mut self,
        query: &AuthAttemptQuery,
        reason: ProviderError,
    ) -> Result<AuthAttemptState, ProviderError> {
        if let Some(terminal) = self.check(query)? {
            return Ok(terminal);
        }
        self.pending.remove(&query.attempt_id);
        Ok(AuthAttemptState::Failed { reason })
    }

    pub fn cancel(&mut self, query: &AuthAttemptQuery) -> Result<AuthAttemptState, ProviderError> {
        if let Some(terminal) = self.check(query)? {
            return Ok(terminal);
        }
        self.pending.remove(&query.attempt_id);
        Ok(AuthAttemptState::Cancelled)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const ID: &str = "oauth_state_from_csprng_0123456789abcdef";

    fn owner(method: &str) -> AuthStart {
        AuthStart {
            scope: "user".into(),
            provider_id: "openai".into(),
            connection_id: "chatgpt".into(),
            method_id: method.into(),
        }
    }
    fn query() -> AuthAttemptQuery {
        AuthAttemptQuery {
            scope: "user".into(),
            provider_id: "openai".into(),
            connection_id: "chatgpt".into(),
            attempt_id: ID.into(),
        }
    }
    fn browser(url: &str) -> AuthChallenge {
        AuthChallenge::OpenBrowser {
            attempt_id: ID.into(),
            url: url.into(),
        }
    }

    #[test]
    fn browser_open_is_never_success_and_account_scope_is_exact() {
        let mut attempts = OAuthAttempts::default();
        let challenge = browser("https://auth.example.com/authorize?state=one");
        assert_eq!(
            attempts.begin(owner("oauth"), challenge.clone()).unwrap(),
            challenge
        );
        assert_eq!(attempts.poll(&query()).unwrap(), AuthAttemptState::Pending);
        let mut foreign = query();
        foreign.connection_id = "api".into();
        assert_eq!(
            attempts.cancel(&foreign).unwrap_err().code,
            ProviderErrorCode::NotFound
        );
        assert_eq!(attempts.poll(&query()).unwrap(), AuthAttemptState::Pending);
        assert_eq!(
            attempts
                .complete(
                    &query(),
                    AuthenticatedProfile {
                        id: "subject".into(),
                        label: "Subject".into(),
                        method_id: "api-key".into()
                    },
                )
                .unwrap_err()
                .code,
            ProviderErrorCode::InvalidInput,
        );
        assert_eq!(attempts.poll(&query()).unwrap(), AuthAttemptState::Pending);
        assert!(matches!(
            attempts.complete(
                &query(),
                AuthenticatedProfile {
                    id: "subject".into(),
                    label: "Subject".into(),
                    method_id: "oauth".into()
                },
            ),
            Ok(AuthAttemptState::Completed { .. })
        ));
        assert_eq!(
            attempts.poll(&query()).unwrap_err().code,
            ProviderErrorCode::NotFound
        );
    }

    #[test]
    fn reissued_challenge_is_observed_once_and_cancel_is_terminal() {
        let mut attempts = OAuthAttempts::default();
        attempts
            .begin(
                owner("oauth"),
                browser("https://auth.example.com/authorize?state=a"),
            )
            .unwrap();
        let rotated = browser("https://auth.example.com/authorize?state=b");
        attempts.reissue(&query(), rotated.clone()).unwrap();
        assert_eq!(
            attempts.poll(&query()).unwrap(),
            AuthAttemptState::AwaitingInput { challenge: rotated }
        );
        assert_eq!(attempts.poll(&query()).unwrap(), AuthAttemptState::Pending);
        assert_eq!(
            attempts.cancel(&query()).unwrap(),
            AuthAttemptState::Cancelled
        );
        assert_eq!(
            attempts.cancel(&query()).unwrap_err().code,
            ProviderErrorCode::NotFound
        );
    }

    #[test]
    fn rejects_forged_challenges_and_expires_without_completing() {
        let mut attempts = OAuthAttempts::default();
        assert_eq!(
            attempts
                .begin(owner("oauth"), browser("http://untrusted.example/"))
                .unwrap_err()
                .code,
            ProviderErrorCode::InvalidInput,
        );
        assert_eq!(
            attempts
                .begin(
                    owner("oauth"),
                    AuthChallenge::ApiKeyInput {
                        attempt_id: ID.into(),
                        prompt: "key".into()
                    }
                )
                .unwrap_err()
                .code,
            ProviderErrorCode::InvalidInput,
        );
        attempts
            .begin(owner("oauth"), browser("https://auth.example.com/"))
            .unwrap();
        assert_eq!(
            attempts
                .begin(owner("oauth"), browser("https://auth.example.com/"))
                .unwrap_err()
                .code,
            ProviderErrorCode::Conflict,
        );
        attempts.pending.get_mut(ID).unwrap().started =
            Instant::now() - ATTEMPT_TTL - std::time::Duration::from_secs(1);
        assert_eq!(attempts.poll(&query()).unwrap(), AuthAttemptState::Expired);
        assert_eq!(
            attempts.poll(&query()).unwrap_err().code,
            ProviderErrorCode::NotFound
        );
    }
}
